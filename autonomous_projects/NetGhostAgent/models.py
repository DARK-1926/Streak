"""
NetGhostAgent Data Models

This module defines the core data structures used throughout the NetGhostAgent
system for representing network events and detected anomalies.
"""

from dataclasses import dataclass
from enum import Enum, auto
from typing import Optional


class EventType(Enum):
    """
    Enumeration of supported network event types.
    
    These events are extracted from standard syslog text and processed
    by the state-machine engine to detect network contradictions.
    """
    DHCP_ASSIGN = auto()
    DHCP_RELEASE = auto()
    ARP_UPDATE = auto()
    NAT_TRANSLATE = auto()


@dataclass(frozen=True)
class LogEvent:
    """
    Represents a single parsed network log event.
    
    Attributes:
        timestamp: The chronological timestamp of the event (e.g., Unix epoch).
        event_type: The specific type of network event that occurred.
        ip: The primary IP address associated with the event.
        mac: The MAC address associated with the event, if applicable.
        port: The network port associated with the event, if applicable.
    """
    timestamp: int
    event_type: EventType
    ip: str
    mac: Optional[str] = None
    port: Optional[int] = None


@dataclass(frozen=True)
class Anomaly:
    """
    Represents a detected network anomaly or contradiction.
    
    Anomalies are generated by the state-machine engine when it detects
    invalid state transitions, such as NAT translations for IPs lacking
    active DHCP leases or ARP entries.
    
    Attributes:
        timestamp: The chronological timestamp when the anomaly was detected.
        ip: The IP address involved in the anomalous behavior.
        description: A detailed, human-readable description of the anomaly.
    """
    timestamp: int
    ip: str
    description: str