import sqlite3
import json
from datetime import datetime
from functools import lru_cache
from typing import List, Dict, Any, Optional

import pandas as pd


DB_PATH = "insightpulse.db"


@lru_cache(maxsize=1)
def get_connection() -> sqlite3.Connection:
    """
    Return a cached SQLite connection.

    The connection is opened with `detect_types=sqlite3.PARSE_DECLTYPES` to allow
    proper handling of `datetime` objects. The same connection instance is reused
    throughout the application lifecycle, which is safe for the typical single‑threaded
    Streamlit usage pattern.

    Returns
    -------
    sqlite3.Connection
        Cached SQLite connection object.
    """
    conn = sqlite3.connect(
        DB_PATH,
        detect_types=sqlite3.PARSE_DECLTYPES | sqlite3.PARSE_COLNAMES,
        check_same_thread=False,
    )
    conn.row_factory = sqlite3.Row
    return conn


def init_db() -> None:
    """
    Initialise the database schema.

    Creates the ``issues`` table if it does not already exist. The table stores:
        - id: integer primary key
        - title: short description
        - description: detailed description
        - tags: JSON‑encoded list of strings
        - created_at: UTC timestamp
    """
    conn = get_connection()
    try:
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS issues (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                title TEXT NOT NULL,
                description TEXT,
                tags TEXT,               -- JSON encoded list
                created_at TIMESTAMP NOT NULL
            )
            """
        )
        conn.commit()
    finally:
        # Do not close the cached connection; it will be reused.
        pass


def add_issue(title: str, description: str, tags: List[str]) -> int:
    """
    Insert a new issue record.

    Parameters
    ----------
    title : str
        Short title of the issue.
    description : str
        Detailed description.
    tags : List[str]
        List of tags generated by the LLM.

    Returns
    -------
    int
        The row id of the newly inserted issue.
    """
    conn = get_connection()
    created_at = datetime.utcnow()
    tags_json = json.dumps(tags)
    cursor = conn.execute(
        """
        INSERT INTO issues (title, description, tags, created_at)
        VALUES (?, ?, ?, ?)
        """,
        (title, description, tags_json, created_at),
    )
    conn.commit()
    return cursor.lastrowid


def fetch_all() -> List[Dict[str, Any]]:
    """
    Retrieve all issues as a list of dictionaries.

    Returns
    -------
    List[Dict[str, Any]]
        Each dictionary contains ``id``, ``title``, ``description``, ``tags`` (as list),
        and ``created_at`` (as ``datetime``).
    """
    conn = get_connection()
    rows = conn.execute(
        """
        SELECT id, title, description, tags, created_at
        FROM issues
        ORDER BY created_at DESC
        """
    ).fetchall()

    result: List[Dict[str, Any]] = []
    for row in rows:
        tags = json.loads(row["tags"]) if row["tags"] else []
        result.append(
            {
                "id": row["id"],
                "title": row["title"],
                "description": row["description"],
                "tags": tags,
                "created_at": row["created_at"],
            }
        )
    return result


def fetch_stats() -> pd.DataFrame:
    """
    Produce analytics data for the UI.

    The returned DataFrame contains one row per issue‑tag combination with columns:
        - id
        - title
        - tag
        - week (ISO week string, e.g. ``2023-W15``)
        - created_at

    Additionally, the function attaches a ``weekly_counts`` attribute – a pandas Series
    indexed by week with the number of issues logged that week (regardless of tags).

    Returns
    -------
    pd.DataFrame
        Exploded tag view suitable for grouping / plotting.
    """
    conn = get_connection()
    df = pd.read_sql_query(
        """
        SELECT id, title, tags, created_at
        FROM issues
        """,
        conn,
        parse_dates=["created_at"],
    )

    # Ensure tags column is a list
    df["tags"] = df["tags"].apply(lambda x: json.loads(x) if x else [])

    # Explode tags
    exploded = df.explode("tags").rename(columns={"tags": "tag"})

    # Compute ISO week string
    exploded["week"] = exploded["created_at"].dt.strftime("%G-W%V")

    # Weekly total counts (ignoring tags)
    weekly_counts = (
        df.groupby(df["created_at"].dt.strftime("%G-W%V"))
        .size()
        .rename("issue_count")
        .sort_index()
    )

    # Attach as attribute for convenient access in the UI
    exploded.attrs["weekly_counts"] = weekly_counts

    return exploded


# Ensure the database is ready as soon as the module is imported
init_db()