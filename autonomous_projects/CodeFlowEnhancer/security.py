    def check_for_suspicious_patterns(file_content: str) -> List[str]:
        """Check the file content for any suspicious patterns that might indicate a security risk."""
        matches = []
        for pattern in SUSPICIOUS_PATTERNS:
            if re.search(pattern, file_content):
                matches.append(pattern)
        return matches

    def scan_file(file_path: str) -> Dict[str, Union[bool, List[str]]]:
        """Scan a single file for potential security issues."""
        with open(file_path, 'r', encoding='utf-8') as file:
            content = file.read()
        
        is_safe = not bool(check_for_suspicious_patterns(content))
        suspicious_patterns = check_for_suspicious_patterns(content)
        
        return {
            "is_safe": is_safe,
            "suspicious_patterns": suspicious_patterns
        }

    def scan_directory(directory: str) -> Dict[str, Dict[str, Union[bool, List[str]]]]:
        """Recursively scan all files in a directory for potential security issues."""
        results = {}
        for root, dirs, files in os.walk(directory):
            for name in files:
                file_path = os.path.join(root, name)
                results[file_path] = scan_file(file_path)
        return results

