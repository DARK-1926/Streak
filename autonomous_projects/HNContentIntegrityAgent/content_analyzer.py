import re
from typing import List, Tuple

def load_patterns(file_path: str) -> List[Tuple[str, str]]:
    """
    Load patterns from a file. Each line in the file should contain a pattern and its description separated by a comma.
    
    :param file_path: Path to the file containing patterns.
    :return: A list of tuples where each tuple contains a regex pattern and its description.
    """
    patterns = []
    try:
        with open(file_path, 'r') as file:
            for line in file:
                if line.strip():
                    parts = line.strip().split(',', 1)
                    if len(parts) == 2:
                        pattern, description = parts
                        patterns.append((re.compile(pattern), description))
    except Exception as e:
        print(f"Failed to load patterns: {e}")
    return patterns

def analyze_text(text: str, patterns: List[Tuple[re.Pattern, str]]) -> bool:
    """
    Analyze the given text against a set of predefined patterns to determine if it is AI-generated.
    
    :param text: The text to be analyzed.
    :param patterns: A list of tuples where each tuple contains a regex pattern and its description.
    :return: True if the text is likely to be AI-generated, False otherwise.
    """
    ai_generated_likelihood = 0
    for pattern, description in patterns:
        if pattern.search(text):
            ai_generated_likelihood += 1
    return ai_generated_likelihood > 0

# Example usage
if __name__ == "__main__":
    patterns = load_patterns('patterns.txt')
    sample_text = "This is a sample text that might or might not be generated by an AI."
    result = analyze_text(sample_text, patterns)
    print(f"Is the text AI-generated? {result}")