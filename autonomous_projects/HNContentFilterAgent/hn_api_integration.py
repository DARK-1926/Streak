from typing import List, Dict, Any
import text_analysis

HN_API_URL = "https://hacker-news.firebaseio.com/v0"

def get_hn_stories(story_type: str, limit: int = 50) -> List[Dict[str, Any]]:
    """
    Fetches a list of stories from the Hacker News API based on the specified story type.
    
    Args:
        story_type (str): The type of stories to fetch (e.g., 'topstories', 'newstories').
        limit (int, optional): The maximum number of stories to fetch. Defaults to 50.
        
    Returns:
        List[Dict[str, Any]]: A list of dictionaries, each representing a story.
    """
    try:
        response = requests.get(f"{HN_API_URL}/{story_type}.json")
        response.raise_for_status()
        story_ids = response.json()[:limit]
        
        stories = []
        for story_id in story_ids:
            story_response = requests.get(f"{HN_API_URL}/item/{story_id}.json")
            if story_response.status_code == 200:
                story = story_response.json()
                if 'text' in story:
                    stories.append(story)
        
        return stories
    except requests.exceptions.RequestException as e:
        print(f"Error fetching stories: {e}")
        return []

def flag_story(story: Dict[str, Any]) -> bool:
    """
    Flags a story as AI-generated by analyzing its content.
    
    Args:
        story (Dict[str, Any]): The story to be analyzed.
        
    Returns:
        bool: True if the story is flagged as AI-generated, False otherwise.
    """
    if 'text' in story:
        text = story['text']
        return text_analysis.analyze_text(text)
    return False
